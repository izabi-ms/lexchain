"""
pdf_security.py
================

This module provides helper functions to watermark and encrypt PDF documents
for LexChain. It uses the PyPDF2 library to read and modify PDF files and
cryptography's AESGCM for strong authenticated encryption. A hidden
"watermark" containing the document ID and hash is written into the PDF
metadata so that any tampering can later be detected. The encrypted file
contains the concatenation of the random initialization vector (IV) and the
cipher‑text generated by AES‑GCM.

Usage
-----

The `add_watermark_and_encrypt` function expects a document ID and its
corresponding document hash along with paths to the input PDF and output
encrypted file. A 256‑bit AES key (32 bytes) must be provided; typically
this will be loaded from an environment variable. The companion
`decrypt_and_verify` function performs decryption and verifies that the
embedded watermark matches the expected document ID and hash.

Note
----
PyPDF2 and cryptography must be installed. These dependencies have been
added to the backend/requirements.txt file. If they are missing, install
them via pip:

    pip install PyPDF2 cryptography reportlab

"""

from __future__ import annotations

import base64
import io
import os
from pathlib import Path
from typing import Tuple

try:
    from PyPDF2 import PdfReader, PdfWriter
except ImportError as e:
    raise ImportError(
        "PyPDF2 is required for PDF watermarking. Please install it via pip: pip install PyPDF2"
    ) from e

try:
    from cryptography.hazmat.primitives.ciphers.aead import AESGCM
except ImportError as e:
    raise ImportError(
        "cryptography is required for AES encryption. Please install it via pip: pip install cryptography"
    ) from e

def _load_key_from_env() -> bytes:
    """Load a base64‑encoded AES key from the environment.

    The key must be stored in the environment variable PDF_ENCRYPTION_KEY. It
    should be a base64 string representing 32 random bytes (256‑bit key).
    If the variable is not set, a hard‑coded fallback key is used. The
    fallback ensures the system operates out of the box in development
    environments but MUST be overridden in production for security.
    """
    key_b64 = os.getenv("PDF_ENCRYPTION_KEY")
    if not key_b64:
        # Fallback key (32 bytes). Replace this with a secure value in production.
        # Generated once using os.urandom(32) and base64.b64encode(key).decode().
        key_b64 = "yNtbYk3A3Nzp3uUnQrRZ9QvOssGdfXBrC/9V4aI4Yxw="
    try:
        return base64.b64decode(key_b64)
    except Exception as exc:
        raise ValueError("Invalid base64 key for PDF_ENCRYPTION_KEY") from exc

def add_watermark_and_encrypt(
    document_id: int,
    document_hash: str,
    pdf_path: Path,
    encrypted_path: Path,
    key: bytes | None = None,
) -> None:
    """Add a hidden watermark to a PDF and encrypt it using AES‑GCM.

    Parameters
    ----------
    document_id: int
        The internal identifier for the document. Used to embed in the watermark.
    document_hash: str
        The keccak256 or other hash of the document's contents. Used in the watermark.
    pdf_path: Path
        Path to the existing PDF to be watermarked.
    encrypted_path: Path
        Path where the encrypted file should be written.
    key: bytes, optional
        A 32‑byte AES key. If omitted, this will be loaded from the environment via
        PDF_ENCRYPTION_KEY.

    Raises
    ------
    FileNotFoundError
        If the input PDF does not exist.
    Exception
        For any underlying I/O or encryption errors.
    """
    if key is None:
        key = _load_key_from_env()
    if len(key) != 32:
        raise ValueError("Encryption key must be 32 bytes (256 bits) long")
    if not pdf_path.is_file():
        raise FileNotFoundError(f"Input PDF does not exist: {pdf_path}")

    # Read the input PDF and copy pages
    reader = PdfReader(str(pdf_path))
    writer = PdfWriter()
    for page in reader.pages:
        writer.add_page(page)

    # Construct a watermark string. This will be stored in PDF metadata under
    # the custom key "/Watermark". Because PDF metadata is not displayed in most
    # viewers, it acts as a hidden marker. Tampering with the PDF (e.g., by
    # re‑saving or editing) typically strips or alters metadata, allowing us to
    # detect modifications during verification.
    watermark_text = f"LexChainID:{document_id};Hash:{document_hash}"
    # Merge existing metadata with our watermark. PdfReader may return None for
    # metadata if the file lacks it, so default to an empty dict.
    existing_metadata = reader.metadata or {}
    metadata = {**existing_metadata, "/Watermark": watermark_text}
    writer.add_metadata(metadata)

    # Write the watermarked PDF to an in‑memory buffer
    buffer = io.BytesIO()
    writer.write(buffer)
    pdf_bytes = buffer.getvalue()

    # Encrypt the watermarked PDF using AES‑GCM. A 12‑byte nonce (IV) is
    # generated randomly for each encryption. AESGCM returns ciphertext that
    # includes the authentication tag at the end. We write IV + ciphertext to
    # the output file.
    iv = os.urandom(12)
    aesgcm = AESGCM(key)
    encrypted_data = aesgcm.encrypt(iv, pdf_bytes, None)
    # Ensure parent directory exists
    encrypted_path.parent.mkdir(parents=True, exist_ok=True)
    with open(encrypted_path, "wb") as f:
        f.write(iv + encrypted_data)

def decrypt_and_verify(
    document_id: int,
    document_hash: str,
    encrypted_path: Path,
    key: bytes | None = None,
) -> Tuple[bool, bytes | None]:
    """Decrypt an encrypted PDF and verify its hidden watermark.

    Parameters
    ----------
    document_id: int
        The expected document ID to compare with the watermark.
    document_hash: str
        The expected document hash to compare with the watermark.
    encrypted_path: Path
        Path to the encrypted file created by `add_watermark_and_encrypt`.
    key: bytes, optional
        A 32‑byte AES key. If omitted, loaded from environment.

    Returns
    -------
    Tuple[bool, bytes | None]
        A tuple `(is_valid, pdf_bytes)`. `is_valid` is True if decryption
        succeeds and the watermark matches the expected document ID and hash.
        `pdf_bytes` contains the decrypted PDF data when decryption succeeds;
        otherwise it is None.

    Raises
    ------
    FileNotFoundError
        If the encrypted file does not exist.
    Exception
        For any decryption errors.
    """
    if key is None:
        key = _load_key_from_env()
    if len(key) != 32:
        raise ValueError("Encryption key must be 32 bytes (256 bits) long")
    if not encrypted_path.is_file():
        raise FileNotFoundError(f"Encrypted file does not exist: {encrypted_path}")

    with open(encrypted_path, "rb") as f:
        data = f.read()
    if len(data) < 13:
        raise ValueError("Encrypted file is too short to contain IV and data")
    iv, ciphertext = data[:12], data[12:]
    aesgcm = AESGCM(key)
    try:
        pdf_data = aesgcm.decrypt(iv, ciphertext, None)
    except Exception:
        # Decryption failed (wrong key or tampered ciphertext)
        return False, None
    # Verify watermark inside metadata
    reader = PdfReader(io.BytesIO(pdf_data))
    metadata = reader.metadata or {}
    watermark = metadata.get("/Watermark")
    expected = f"LexChainID:{document_id};Hash:{document_hash}"
    if watermark != expected:
        return False, pdf_data
    return True, pdf_data




